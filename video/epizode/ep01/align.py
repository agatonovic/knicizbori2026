R=12.22
import functools
n,m=len(units),len(segs)
@functools.lru_cache(None)
def f(i,j):
    if i==n and j==m: return (0,[])
    best=(1e9,[])
    for a in range(1,5):
        for b in range(1,4):
            if a>1 and b>1: continue
            if i+a>n or j+b>m: continue
            ch=sum(L[i:i+a]); d=segs[j+b-1][1]-segs[j][0]
            c=(d-ch/R)**2
            r=f(i+a,j+b)
            if c+r[0]<best[0]: best=(c+r[0],[(i,a,j,b)]+r[1])
    return best
